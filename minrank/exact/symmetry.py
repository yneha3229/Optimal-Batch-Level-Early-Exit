"""Symmetry breaking for the minrank SAT encoding, graph automorphisms, and a timed CNF solver.

Encoding (same variables as minrank/exact/sat.py: u[i][k] = 1 + i r + k, v[j][k] = 1 + n r + j r + k):
    <u_i, v_i> = 1, <u_i, v_j> = 0 for every forbidden (i, j); AND gates + XOR chains.

Symmetries of the solution set {(U, V) : U V^T fits G, width r}
---------------------------------------------------------------
(G1) GL(r, F_2):  (U, V) -> (U W, V W^{-T}). Contains the column permutations (W a permutation matrix).
(G2) Aut(G):      (U, V) -> (P_s U, P_s V), (P_s U)_i = u_{s(i)}, for an automorphism s of G (s maps non-edges to
                  non-edges, so the permuted product still fits).

Modes (all sound; tests compare every mode with brute force on small graphs)
-------------------------------------------------------------------------------
"none":   base clauses only.
"u0":     u_0 = e_1 (as in sat.py). Sound: u_0 != 0 because A[0,0] = 1, and some W in GL(r) maps u_0 to e_1.
"cols":   "u0" + columns 1..r-1 non-decreasing in lex order of the interleaved column vector
          c_k = (u_0k, v_0k, u_1k, v_1k, ..., u_{n-1,k}, v_{n-1,k}). Sound: given any solution with u_0 = e_1,
          permuting columns 1..r-1 into sorted order keeps u_0 = e_1 (those coordinates of u_0 are 0) and keeps
          U V^T; the sorted solution satisfies the constraints.
"aut":    no u_0 fix. Lex-leader constraints w <= g(w) for the generators g of a group acting on the variable vector
          w in ROW-MAJOR order (row i = u_i0..u_i,r-1, v_i0..v_i,r-1, rows in vertex order):
            - column transpositions (k, k+1) for k = 0..r-2; in row-major order w <= tau_k(w) is exactly
              c_k <=_lex c_{k+1} with the interleaved column vector above (first differing position is u_ik or
              v_ik of the smallest row where columns k and k+1 differ, and u comes before v in a row);
            - the automorphism generators s of G found by `automorphisms`.
          Sound: all constraints are of the form w <= g(w) for g in the group generated by these maps, for ONE fixed
          variable order; the lexicographically smallest element of any orbit satisfies all of them, and the orbit
          of a solution consists of solutions. (Using a subset of generators only weakens the constraints.)
"indep":  independent-set fix, given a vertex set I (|I| = s; if s > r the answer is UNSAT by the L1 bound and no
          CNF is needed). Let A = U V^T fit G.
          - If I induces no arc, A[I, I] = Id, so U_I has full row rank s. Some W in GL(r) gives U_I W = [Id_s | 0];
            then V_I W^{-T} = [Id_s | X], and W' = [[Id, 0], [X^T, Id]] fixes U_I and sends X to 0. Hence WLOG
            U_I = V_I = [Id_s | 0] (u_{I_k} = v_{I_k} = e_k, I in increasing order).
          - If I is only acyclic (directed G), A[I, I] is unit triangular in a topological order, hence invertible:
            U_I = [Id_s | 0] as before, V_I W^{-T} = [B | X] with B invertible, and W' = [[Id, 0], [(B^{-1} X)^T, Id]]
            sends X to 0. Hence WLOG U_I = [Id_s | 0] and V_I[:, s:] = 0.
          Not combined with u_0 = e_1 (a different normalisation of the same GL(r) freedom).
"indep_cols": "indep" + columns s..r-1 non-decreasing in lex order of the interleaved column vectors (as "cols").
          Sound: permuting columns s..r-1 keeps U V^T and the fixed rows (those columns of U_I, V_I are zero), so
          sorting them maps any "indep" solution to an "indep_cols" solution.
"u0" / "cols" are not combined with automorphisms: u_0 = e_1 is not a lex-leader constraint for row-major order,
so mixing it with w <= s(w) is not obviously sound.
"""
from __future__ import annotations

import time
from typing import Callable, Sequence

from pysat.solvers import Solver

from ..core.graph import Graph, iter_bits
from .lower import is_acyclic_induced
from .sat import _context, _var_u, _var_v

MODES = ("none", "u0", "cols", "aut", "indep", "indep_cols")
INDEP_MODES = ("indep", "indep_cols")


def check_indep(g: Graph, indep: Sequence[int]) -> bool:
    """Validate I for the "indep" modes. Returns True if I induces no arc (full fix U_I = V_I = [Id | 0]), False if it
    is acyclic but has arcs (directed fix: U_I = [Id | 0], V_I[:, s:] = 0); raises ValueError otherwise."""
    verts = list(indep)
    if len(set(verts)) != len(verts) or any(not 0 <= v < g.n for v in verts):
        raise ValueError("indep must be distinct vertices of g")
    mask = sum(1 << v for v in verts)
    if all((g.out[v] & mask) == 0 for v in verts):
        return True
    if not is_acyclic_induced(g, verts):
        raise ValueError("indep must induce an acyclic subgraph")
    return False


class VarPool:
    def __init__(self, top: int) -> None:
        self.top = top

    def new(self) -> int:
        self.top += 1
        return self.top


# ---- lexicographic constraint ----------------------------------------------------------------------------------
def lex_leq(x: Sequence[int], y: Sequence[int], pool: VarPool) -> list[list[int]]:
    """Clauses enforcing x <=_lex y (x, y literal vectors of equal length; True > False).

    e_t means "x and y are equal on positions < t" (only the forcing direction is encoded, which is enough: e only
    occurs negatively in the constraint clauses). Positions with the identical literal are skipped.
    """
    if len(x) != len(y):
        raise ValueError("lex vectors must have equal length")
    pairs = [(a, b) for a, b in zip(x, y) if a != b]
    cls: list[list[int]] = []
    e = None  # None means "true"
    for t, (a, b) in enumerate(pairs):
        pre = [] if e is None else [-e]
        cls.append(pre + [-a, b])  # equal so far -> not (a and not b)  i.e. a <= b
        if t == len(pairs) - 1:
            break
        e2 = pool.new()  # equal so far and a == b -> e2
        cls.append(pre + [-a, -b, e2])
        cls.append(pre + [a, b, e2])
        e = e2
    return cls


# ---- automorphisms ---------------------------------------------------------------------------------------------
def _refine(g: Graph, colors: list[int]) -> list[int]:
    """1-WL colour refinement on the directed graph (out- and in-neighbour colour multisets)."""
    n = g.n
    inc = [0] * n
    for j in range(n):
        for i in iter_bits(g.out[j]):
            inc[i] |= 1 << j
    while True:
        sig = [(colors[v], tuple(sorted(colors[w] for w in iter_bits(g.out[v]))),
                tuple(sorted(colors[w] for w in iter_bits(inc[v])))) for v in range(n)]
        ids = {s: k for k, s in enumerate(sorted(set(sig)))}
        new = [ids[s] for s in sig]
        if len(set(new)) == len(set(colors)):
            return new
        colors = new


def is_automorphism(g: Graph, perm: Sequence[int]) -> bool:
    n = g.n
    if sorted(perm) != list(range(n)):
        return False
    for i in range(n):
        img = 0
        for j in iter_bits(g.out[i]):
            img |= 1 << perm[j]
        if img != g.out[perm[i]]:
            return False
    return True


def automorphisms(g: Graph, max_gens: int = 32, node_limit: int = 200_000) -> list[list[int]]:
    """Some non-identity automorphisms of g (not necessarily a full generating set; any subset is sound to use).

    Individualisation-refinement: for the first vertex v of the first non-singleton cell of the refined partition,
    try to map v to each other vertex w of its cell, refining after each individualisation and backtracking; keep
    the first automorphism found per (v, w). Every result is checked with `is_automorphism`.
    """
    n = g.n
    base = _refine(g, [0] * n)
    nodes = 0
    gens: list[list[int]] = []

    def extend(ca: list[int], cb: list[int]) -> list[int] | None:
        nonlocal nodes
        nodes += 1
        if nodes > node_limit:
            return None
        ca, cb = _refine(g, ca), _refine(g, cb)
        if sorted(ca) != sorted(cb):
            return None
        if len(set(ca)) == n:  # discrete: unique bijection matching colours
            pos = {c: v for v, c in enumerate(cb)}
            perm = [pos[ca[v]] for v in range(n)]
            return perm if is_automorphism(g, perm) else None
        cells: dict[int, list[int]] = {}
        for v, c in enumerate(ca):
            cells.setdefault(c, []).append(v)
        cell = min((c for c in cells if len(cells[c]) > 1), key=lambda c: (len(cells[c]), c))
        x = cells[cell][0]
        fresh = max(max(ca), max(cb)) + 1
        for y in [v for v, c in enumerate(cb) if c == cell]:
            na, nb = list(ca), list(cb)
            na[x], nb[y] = fresh, fresh
            res = extend(na, nb)
            if res is not None:
                return res
        return None

    cells: dict[int, list[int]] = {}
    for v, c in enumerate(base):
        cells.setdefault(c, []).append(v)
    for c in sorted(cells):
        cell = cells[c]
        if len(cell) < 2:
            continue
        v = cell[0]
        for w in cell[1:]:
            if len(gens) >= max_gens or nodes > node_limit:
                return gens
            ca, cb = list(base), list(base)
            fresh = max(base) + 1
            ca[v], cb[w] = fresh, fresh
            perm = extend(ca, cb)
            if perm is not None and perm != list(range(n)) and perm not in gens:
                gens.append(perm)
    return gens


# ---- encoding with symmetry breaking ---------------------------------------------------------------------------
def encode_sym(g: Graph, r: int, mode: str = "cols", gens: Sequence[Sequence[int]] | None = None,
               indep: Sequence[int] | None = None) -> list[list[int]]:
    """CNF for minrk_2(G) <= r with the chosen symmetry-breaking mode (see module docstring). The "indep" modes need
    `indep`, a vertex set inducing no arc (undirected: an independent set) or an acyclic subgraph, with |indep| <= r."""
    if mode not in MODES:
        raise ValueError(f"mode must be one of {MODES}")
    n = g.n
    if not 1 <= r <= n:
        raise ValueError(f"need 1 <= r <= n, got r={r}, n={n}")
    pool = VarPool(2 * n * r)
    U = [[_var_u(n, r, i, k) for k in range(r)] for i in range(n)]
    V = [[_var_v(n, r, j, k) for k in range(r)] for j in range(n)]
    cnf: list[list[int]] = []
    for i in range(n):
        for j in [i] + list(iter_bits(g.forbidden(i))):
            prev = None
            for k in range(r):
                z = pool.new()
                a, b = U[i][k], V[j][k]
                cnf += [[-z, a], [-z, b], [z, -a, -b]]
                if prev is None:
                    prev = z
                    continue
                x = pool.new()
                cnf += [[-x, prev, z], [-x, -prev, -z], [x, -prev, z], [x, prev, -z]]
                prev = x
            cnf.append([prev] if i == j else [-prev])
    if mode in ("u0", "cols"):
        cnf.append([U[0][0]])
        cnf += [[-U[0][k]] for k in range(1, r)]
    first = {"cols": 1, "aut": 0}.get(mode)
    if mode in INDEP_MODES:
        if indep is None:
            raise ValueError(f"mode {mode!r} needs indep")
        full = check_indep(g, indep)
        s = len(indep)
        if s > r:
            raise ValueError(f"|indep| = {s} > r = {r}: UNSAT by the L1 bound, no CNF needed")
        for k, i in enumerate(sorted(indep)):
            for c in range(r):
                cnf.append([U[i][c]] if c == k else [-U[i][c]])
                if full:
                    cnf.append([V[i][c]] if c == k else [-V[i][c]])
                elif c >= s:
                    cnf.append([-V[i][c]])
        if mode == "indep_cols":
            first = s
    if first is not None:

        def col(k: int) -> list[int]:
            return [lit for i in range(n) for lit in (U[i][k], V[i][k])]

        for k in range(first, r - 1):
            cnf += lex_leq(col(k), col(k + 1), pool)
    if mode == "aut":
        w = [lit for i in range(n) for lit in U[i] + V[i]]  # row-major variable order
        for s in (gens if gens is not None else automorphisms(g)):
            if not is_automorphism(g, s):
                raise ValueError("not an automorphism")
            sw = [lit for i in range(n) for lit in U[s[i]] + V[s[i]]]  # (P_s w): row i = row s(i)
            cnf += lex_leq(w, sw, pool)
    return cnf


# ---- timed solving in a forkserver child -----------------------------------------------------------------------
def _child(conn, build: Callable[..., list[list[int]]], args: tuple, solver: str) -> None:
    import traceback

    try:
        cnf = build(*args)
        with Solver(name=solver, bootstrap_with=cnf) as s:
            msg = ("ok", s.get_model() if s.solve() else None)
    except BaseException:
        msg = ("err", traceback.format_exc())
    try:
        conn.send(msg)
    finally:
        conn.close()


def solve_timed(build: Callable[..., list[list[int]]], args: tuple, time_limit: float | None,
                solver: str = "cadical153") -> list[int] | bool | None:
    """Build and solve a CNF; model if SAT, False if UNSAT, None on timeout. `build` must be a module-level
    function (it is pickled to a forkserver child). The limit counts building, start-up and solving."""
    if time_limit is None:
        cnf = build(*args)
        with Solver(name=solver, bootstrap_with=cnf) as s:
            return s.get_model() if s.solve() else False
    t0 = time.perf_counter()
    ctx = _context()
    parent, child = ctx.Pipe(duplex=False)
    p = ctx.Process(target=_child, args=(child, build, args, solver), daemon=True)
    started = False
    try:
        p.start()
        started = True
        child.close()
        if not parent.poll(max(0.0, time_limit - (time.perf_counter() - t0))):
            p.kill()
            return None
        try:
            status, payload = parent.recv()
        except EOFError:
            p.join()
            raise RuntimeError(f"SAT child exited without a result (exit code {p.exitcode})") from None
        if status == "err":
            raise RuntimeError(f"SAT child failed:\n{payload}")
        return payload if payload is not None else False
    finally:
        parent.close()
        if started:
            p.join()
        else:
            child.close()


def rank_at_most_sym(g: Graph, r: int, time_limit: float | None = None, mode: str = "cols",
                     gens: Sequence[Sequence[int]] | None = None, solver: str = "cadical153",
                     indep: Sequence[int] | None = None, lb_time: float = 30.0) -> list[int] | bool | None:
    """Like sat.rank_at_most, with symmetry breaking. Verified rows if SAT, False if UNSAT, None on timeout.

    The "indep" modes use `indep` (default: the acyclic set found by `lower.mais` in `lb_time` s). If it has more than
    r vertices, the answer is False without a SAT call (L1 lower bound: minrk >= |indep|)."""
    import numpy as np

    from ..core.f2 import rows_from_factors
    from ..core.verify import verify

    if mode == "aut" and gens is None:
        gens = automorphisms(g)
    if mode in INDEP_MODES:
        if indep is None:
            from .lower import mais

            indep = mais(g, lb_time).vertices
        check_indep(g, indep)
        if len(indep) > r:
            return False
        indep = [int(v) for v in indep]
    res = solve_timed(encode_sym, (g, r, mode, [list(s) for s in gens] if gens is not None else None, indep),
                      time_limit, solver)
    if res is None or res is False:
        return res
    model = set(x for x in res if x > 0)
    n = g.n
    U = np.array([[1 if _var_u(n, r, i, k) in model else 0 for k in range(r)] for i in range(n)], dtype=np.uint8)
    V = np.array([[1 if _var_v(n, r, i, k) in model else 0 for k in range(r)] for i in range(n)], dtype=np.uint8)
    rows = rows_from_factors(U, V)
    if verify(g, rows) > r:
        raise RuntimeError("SAT model exceeds the rank bound")
    return rows
