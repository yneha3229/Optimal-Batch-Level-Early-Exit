"""The classical discrete-log algorithms, each as  solve(inst, limit) -> (x or None, info).

  bsgs            baby-step giant-step over the full order of g: O(sqrt(n)) time and memory
  rho             Pollard's rho for discrete logs (Floyd cycle finding): O(sqrt(n)) time, O(1) memory
  kangaroo        Pollard's kangaroo (lambda): O(sqrt(interval)) when the exponent lies in a known interval
  pohlig_hellman  factor n, solve each prime-power subgroup (bsgs for small, rho for larger), combine by CRT
  pari_generic    PARI's own solver (znlog in F_p*, elllog on curves): Pohlig-Hellman + index calculus

Each runs in its own process with a hard time limit (see harness), so an unfinished sqrt(n) loop is just killed.
"""
from __future__ import annotations

import math
import time

from .group import EC, Fp, Instance


def _isqrt_ceil(n):
    r = math.isqrt(n)
    return r + 1 if r * r < n else r


def bsgs(G, g, h, n, limit_elts=None):
    """Smallest x in [0, n) with g^x = h, by baby-step giant-step. limit_elts caps the table size (returns None)."""
    m = _isqrt_ceil(n)
    if limit_elts and m > limit_elts:
        return None
    table = {}
    e = G.identity
    for j in range(m):
        table.setdefault(G.key(e), j)
        e = G.op(e, g)
    factor = G.inv(G.pow(g, m))     # g^{-m}
    gamma = h
    for i in range(m):
        j = table.get(G.key(gamma))
        if j is not None:
            return (i * m + j) % n
        gamma = G.op(gamma, factor)
    return None


def _rho_f(G, g, h, n, x, a, b):
    """One step of the r=3 partition iteration for g^a h^b = x."""
    s = G.key(x)
    r = (s[0] if isinstance(s, tuple) else s) % 3
    if r == 0:
        return G.op(x, g), (a + 1) % n, b
    if r == 1:
        return G.op(x, x), (2 * a) % n, (2 * b) % n
    return G.op(x, h), a, (b + 1) % n


def rho(G, g, h, n, limit=None):
    """Pollard's rho with Floyd cycle finding; restarts on a degenerate collision."""
    t0 = time.perf_counter()
    import random

    rng = random.Random(12345)
    for _ in range(20):
        a0, b0 = rng.randrange(n), rng.randrange(n)
        x = G.op(G.pow(g, a0), G.pow(h, b0))
        tx, ta, tb = x, a0, b0
        hx, ha, hb = x, a0, b0
        steps = 0
        while True:
            tx, ta, tb = _rho_f(G, g, h, n, tx, ta, tb)
            hx, ha, hb = _rho_f(G, g, h, n, *_rho_f(G, g, h, n, hx, ha, hb))
            steps += 1
            if G.eq(tx, hx):
                db = (tb - hb) % n
                num = (ha - ta) % n
                if db == 0:
                    break
                d = math.gcd(db, n)
                if d == 1:
                    x = num * pow(db, -1, n) % n
                    if G.eq(G.pow(g, x), h):
                        return x
                    break
                if num % d:
                    break
                m = n // d                       # d candidate solutions, spaced by m
                x0 = (num // d) * pow(db // d, -1, m) % m
                for t in range(d):
                    x = (x0 + t * m) % n
                    if G.eq(G.pow(g, x), h):
                        return x
                break
            if limit and (steps & 0x3FFF) == 0 and time.perf_counter() - t0 > limit:
                return None
    return None


def kangaroo(G, g, h, b, limit=None):
    """Exponent in [0, b]: Pollard's kangaroo. ~2 sqrt(b) group operations."""
    t0 = time.perf_counter()
    if b <= 0:
        return 0 if G.eq(h, G.identity) else None
    k = max(1, int(0.5 * math.log2(b + 1)))
    jumps = [1 << i for i in range(k)]
    mean = sum(jumps) // len(jumps)

    def jump_idx(x):
        s = G.key(x)
        v = (s[0] if isinstance(s, tuple) else s)
        return v % k

    N = int(4 * math.isqrt(b + 1)) + 10
    xt = G.pow(g, b)                 # tame kangaroo starts at g^b
    dt = 0
    for _ in range(N):
        j = jumps[jump_idx(xt)]
        xt = G.op(xt, G.pow(g, j))
        dt += j
    trap = G.key(xt)
    xw, dw = h, 0                    # wild kangaroo starts at h = g^x
    steps = 0
    while dw <= b + dt:
        if G.key(xw) == trap:
            x = (b + dt - dw)
            if 0 <= x <= b and G.eq(G.pow(g, x), h):
                return x
            return None
        j = jumps[jump_idx(xw)]
        xw = G.op(xw, G.pow(g, j))
        dw += j
        steps += 1
        if limit and (steps & 0x3FFF) == 0 and time.perf_counter() - t0 > limit:
            return None
    return None


def _factor(n):
    import cypari2

    pari = cypari2.Pari()
    f = pari.factor(n)
    return [(int(f[0][i]), int(f[1][i])) for i in range(len(f[0]))]


def _dl_prime_power(G, g, h, n, q, e, limit=None):
    """DL in the cyclic subgroup of order q^e generated by g (which has order n). Digit-by-digit (textbook PH)."""
    x = 0
    gamma = G.pow(g, n // q)                     # element of order q
    for k in range(e):
        exp = n // (q ** (k + 1))
        hk = G.pow(G.op(h, G.inv(G.pow(g, x))), exp)   # (h g^{-x})^{n/q^{k+1}}
        if q <= 1 << 20:
            d = bsgs(G, gamma, hk, q)
        else:
            d = rho(G, gamma, hk, q, limit=limit)
        if d is None:
            return None
        x += d * (q ** k)
    return x


def pohlig_hellman(G, g, h, n, factors=None, limit=None):
    """Full Pohlig-Hellman: reduce to each prime-power subgroup, combine by CRT."""
    if factors is None:
        factors = _factor(n)
    rems, mods = [], []
    for q, e in factors:
        m = q ** e
        cof = n // m
        gi, hi = G.pow(g, cof), G.pow(h, cof)     # both of order dividing m
        xi = _dl_prime_power(G, gi, hi, m, q, e, limit=limit)
        if xi is None:
            return None
        rems.append(xi % m)
        mods.append(m)
    x, M = 0, 1
    for r, m in zip(rems, mods):
        M2 = M * m
        x += M * ((r - x) % m) * pow(M % m if M % m else 1, -1, m) % M2
        x %= M2
        M = M2
    return x % n


def pari_generic(inst: Instance, limit=None):
    import cypari2

    pari = cypari2.Pari()
    pari.allocatemem(1 << 30, silent=True)
    G = inst.group
    if isinstance(G, Fp):
        return int(pari.znlog(pari.Mod(inst.h, G.p), pari.Mod(inst.g, G.p), inst.n))
    E = pari.ellinit([G.a, G.b], G.p)
    toP = lambda P: pari.ellmul(E, [0], 0) if P is None else pari([P[0], P[1]])  # noqa: E731
    return int(pari.elllog(E, toP(inst.h), toP(inst.g), inst.n))


# ---- dispatch -------------------------------------------------------------------------------------------------
def solve(name: str, inst: Instance, limit: float):
    G, g, h, n = inst.group, inst.g, inst.h, inst.n
    if name == "bsgs":
        return bsgs(G, g, h, n)
    if name == "rho":
        return rho(G, g, h, n, limit=limit)
    if name == "kangaroo":
        return None if inst.interval is None else kangaroo(G, g, h, inst.interval, limit=limit)
    if name == "pohlig_hellman":
        return pohlig_hellman(G, g, h, n, limit=limit)
    if name == "pari_generic":
        return pari_generic(inst, limit=limit)
    raise ValueError(name)


METHODS = ["bsgs", "rho", "kangaroo", "pohlig_hellman", "pari_generic"]
